/// <reference types="vitest/config" />
import path from "path"
import react from "@vitejs/plugin-react"
import { defineConfig, type Plugin } from "vite"
import { inspectAttr } from 'kimi-plugin-inspect-react'

/**
 * GitHub Pages serves a project site under `/<repository>/`. CI supplies the
 * real value from `actions/configure-pages` as VITE_BASE; the fallback matches
 * this repository's Pages URL, and an explicit `/` (custom domain/user site)
 * is preserved.
 */
const DEMO_DEFAULT_BASE = '/migraine-tracker/';

function normalizeBase(raw: string | undefined, fallback: string): string {
  const value = raw?.trim();
  if (!value) return fallback;
  if (value === '/') return '/';
  return `/${value.replace(/^\/+|\/+$/g, '')}/`;
}

/**
 * Demo-only HTML marker. `validate:demo` asserts it so a production build can
 * never be uploaded as the demo artifact (and vice versa: the demo build
 * carries the marker and its own title).
 */
function demoMarker(): Plugin {
  return {
    name: 'migraine-demo-marker',
    apply: 'build',
    transformIndexHtml(html) {
      return html
        .replace(
          '<head>',
          '<head>\n    <!-- Generated by `npm run build:demo`; not present in production. -->\n    <meta name="migraine-demo" content="true" />',
        )
        .replace(
          '<title>Migraine Tracker</title>',
          '<title>Migraine Tracker Demo</title>',
        )
        .replace(
          /content="Private migraine tracker[^"]*"/,
          'content="Interactive demo of a private migraine tracker with fictional sample data. Nothing is saved and no server is contacted."',
        );
    },
  };
}

// https://vite.dev/config/
export default defineConfig(({ mode }) => {
  const demo = mode === 'demo';
  // The demo is the writer app only: the backend-polling partner shell
  // (`view.html`) is deliberately not built.
  const input: Record<string, string> = demo
    ? { index: path.resolve(__dirname, 'index.html') }
    : {
      index: path.resolve(__dirname, 'index.html'),
      view: path.resolve(__dirname, 'view.html'),
    };
  return {
    // VITE_BASE is demo-only: production/Docker always stays at the origin root
    // with its existing root-scoped manifests, regardless of ambient CI env.
    base: demo ? normalizeBase(process.env.VITE_BASE, DEMO_DEFAULT_BASE) : '/',
    plugins: demo ? [inspectAttr(), react(), demoMarker()] : [inspectAttr(), react()],
    server: {
      port: 3000,
      proxy: {
        // during local dev, forward API calls to the backend on :3100
        '/api': 'http://localhost:3100',
      },
    },
    resolve: {
      alias: {
        "@": path.resolve(__dirname, "./src"),
      },
    },
    build: {
      // A separate output directory keeps production `dist/` (and its PWA
      // validation) untouched; `dist-demo/` is gitignored.
      outDir: demo ? 'dist-demo' : 'dist',
      rollupOptions: { input },
    },
    test: {
      // Pure unit tests only — the server has its own `node --test` suite
      // (run via `npm test --prefix server`), and no jsdom/network/storage.
      environment: 'node',
      include: ['shared/**/*.test.{ts,tsx}', 'src/**/*.test.{ts,tsx}'],
    },
  };
});
